import { execFileSync } from 'node:child_process';
import { strict as assert } from 'node:assert';
import { randomBytes, randomUUID } from 'node:crypto';
import { appendFile, readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

// Synthetic-only verifier against the REAL carelog-be (no stub). Every account is created through the public
// Gateway registration route. Only statuses, booleans, counts and fixed server messages are printed; tokens,
// passwords, emails, names and account/user ids are never logged.

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const ENROLLMENT_PATH_PREFIX = '/api/v1/internal/v1/identity/carelog/enrollments/';
const CLAIMS_PATH_PREFIX = '/api/v1/internal/identity/claims/';
const ACCESS_LINE = /^(\S+) (\S+) (\d{3}) cl=(\S*) te=(.*)$/;

let stage = 'initialization';
const observed = {};

async function send(method, url, { headers = {}, body } = {}) {
  const init = { method, headers: { accept: 'application/json', ...headers } };
  if (body !== undefined) {
    init.headers['content-type'] = 'application/json';
    init.body = JSON.stringify(body);
  }
  const response = await fetch(url, init);
  const text = await response.text();
  let json = null;
  try {
    json = text ? JSON.parse(text) : null;
  } catch {
    json = null;
  }
  return { status: response.status, json };
}

function expectStatus(result, expected, label) {
  if (result.status !== expected) {
    // Server messages are fixed Core/Gateway strings; they separate a Gateway 503 from a Core 503.
    const message = typeof result.json?.message === 'string' && result.json.message.length <= 120
      ? ` message="${result.json.message}"`
      : '';
    stage = `${label} HTTP ${result.status}${message}`;
    assert.fail(`${label}: expected ${expected}, got ${result.status}`);
  }
  stage = label;
}

function jwtClaims(token) {
  const parts = token.split('.');
  assert.equal(parts.length, 3);
  return JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
}

// Read-only SQL. Every interpolated value is a UUID or a synthetic value generated by this script.
function psqlRows(database, sql) {
  let out;
  try {
    out = execFileSync(
      'psql',
      [
        '-h', process.env.PGHOST ?? '127.0.0.1',
        '-p', process.env.PGPORT ?? '5432',
        '-U', process.env.PGUSER ?? 'postgres',
        '-d', database,
        '-At', '-F', '\t',
        '-v', 'ON_ERROR_STOP=1',
        '-c', sql,
      ],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
    ).trim();
  } catch {
    // Do not surface the command line: it carries synthetic account and login values.
    throw new Error(`psql query failed on ${database} (details withheld)`);
  }
  return out === '' ? [] : out.split('\n').map((line) => line.split('\t'));
}

async function readAccessLog() {
  const dir = process.env.E2E_CARELOG_ACCESS_LOG_DIR;
  assert.ok(dir, 'E2E_CARELOG_ACCESS_LOG_DIR is required');
  const names = (await readdir(dir)).filter((name) => name.startsWith('access_log'));
  const rows = [];
  for (const name of names) {
    const text = await readFile(join(dir, name), 'utf8');
    for (const line of text.split('\n')) {
      const match = ACCESS_LINE.exec(line.trim());
      if (match) {
        rows.push({ method: match[1], path: match[2], status: Number(match[3]), cl: match[4], te: match[5] });
      }
    }
  }
  return rows;
}

// carelog-be writes its access-log line after the response is sent, so re-read for up to ~3s until the
// expected condition holds. Returns the last read either way; the caller's assertion decides.
async function waitForAccessLog(predicate, windowMs = 3000) {
  const deadline = Date.now() + windowMs;
  let rows = await readAccessLog();
  while (!predicate(rows) && Date.now() < deadline) {
    await new Promise((resolve) => setTimeout(resolve, 250));
    rows = await readAccessLog();
  }
  return rows;
}

const countPuts = (rows, accountId) =>
  rows.filter((r) => r.method === 'PUT' && r.path === `${ENROLLMENT_PATH_PREFIX}${accountId}`);
const countClaims200 = (rows, accountId) =>
  rows.filter((r) => r.method === 'GET' && r.path === `${CLAIMS_PATH_PREFIX}${accountId}` && r.status === 200);

async function main() {
  const base = process.env.E2E_GATEWAY_URL;
  const carelogBase = process.env.E2E_CARELOG_URL;
  assert.ok(base && carelogBase, 'gateway and carelog-be URLs are required');
  assert.equal(process.env.CARELOG_ENROLLMENT_TARGET, 'real', 'CARELOG_ENROLLMENT_TARGET must be real');
  console.log('CARELOG_ENROLLMENT_TARGET=real (carelog-be enrollment and claims, no stub)');

  const runId = randomBytes(6).toString('hex');
  const carelog = {
    userId: `carelog-real-e2e-${runId}`,
    email: `carelog-real-e2e-${runId}@example.test`,
    password: 'CarelogRealE2E-pass1',
    name: 'Synthetic Carelog Manager',
  };
  const idempotencyKey = randomUUID();

  // 1. Registration through Gateway -> Core -> real carelog-be enrollment PUT.
  stage = 'Carelog registration through Gateway';
  const registration = await send('POST', `${base}/api/v1/auth/carelog/registration`, {
    headers: { 'idempotency-key': idempotencyKey },
    body: carelog,
  });
  expectStatus(registration, 201, 'Carelog registration through Gateway');
  observed.registration = registration.status;

  // The registration response carries no accountId. The Core operation row (keyed by the Idempotency-Key)
  // and the password credential row (login_id = userId) identify it; both must agree.
  stage = 'Core registration operation row';
  const operationRows = psqlRows('platform_e2e',
    `SELECT account_id, state FROM identity.carelog_registration_operation WHERE operation_key = '${idempotencyKey}'`);
  assert.equal(operationRows.length, 1, 'exactly one Core operation row for the key');
  const [accountId, operationState] = operationRows[0];
  assert.ok(UUID_RE.test(accountId), 'operation row account id must be a UUID');
  observed.coreOperationState = operationState;
  assert.equal(operationState, 'COMPLETED');

  stage = 'Core credential row';
  const credentialRows = psqlRows('platform_e2e',
    `SELECT account_id FROM identity.password_credentials WHERE login_id = '${carelog.userId}'`);
  assert.equal(credentialRows.length, 1, 'exactly one Core credential row for the login id');
  assert.equal(credentialRows[0][0], accountId, 'credential account must match operation account');

  // 2. carelog-be database: the enrollment row exists for the accountId Core enrolled.
  stage = 'carelog-be enrollment row';
  const carelogUsers = psqlRows('carelog_be_e2e',
    `SELECT count(*) FROM users WHERE external_account_id = '${accountId}' AND role = 'MANAGER'`);
  observed.carelogUserRows = Number(carelogUsers[0][0]);
  assert.equal(observed.carelogUserRows, 1, 'carelog-be must hold exactly one MANAGER row for the accountId');

  stage = 'carelog-be projection receipt';
  const receipts = psqlRows('carelog_be_e2e',
    `SELECT count(*) FROM external_manager_projection_receipts
       WHERE external_account_id = '${accountId}' AND initial_user_id = '${carelog.userId}'
         AND initial_email = '${carelog.email}' AND initial_name = '${carelog.name}'`);
  observed.carelogReceiptRows = Number(receipts[0][0]);
  assert.equal(observed.carelogReceiptRows, 1, 'carelog-be must hold exactly one matching projection receipt');

  // 3. carelog-be access log: the enrollment PUT arrived once and was answered 201. Chunking is recorded only.
  stage = 'carelog-be access log after registration';
  let rows = await waitForAccessLog((r) => countPuts(r, accountId).length >= 1);
  const putsAfterRegistration = countPuts(rows, accountId);
  observed.enrollmentPutCount = putsAfterRegistration.length;
  observed.enrollmentPutStatuses = putsAfterRegistration.map((r) => r.status).join(',');
  assert.equal(putsAfterRegistration.length, 1, 'carelog-be must receive exactly one enrollment PUT');
  assert.equal(putsAfterRegistration[0].status, 201, 'carelog-be must answer the enrollment PUT with 201');
  // Core's enrollment PUT must arrive chunked (Transfer-Encoding: chunked) and be accepted with 201.
  assert.ok(putsAfterRegistration[0].te.toLowerCase().includes('chunked'),
    'enrollment PUT for the accountId must arrive with Transfer-Encoding: chunked');
  observed.enrollmentChunked = 'asserted (Transfer-Encoding: chunked, status 201)';

  // 4. Login immediately after signup: 200 token whose sub is the accountId.
  stage = 'Carelog login through Gateway';
  const login = await send('POST', `${base}/api/v1/auth/login`, {
    body: { userId: carelog.userId, password: carelog.password },
  });
  expectStatus(login, 200, 'Carelog login through Gateway');
  assert.equal(typeof login.json?.data?.accessToken, 'string');
  const claims = jwtClaims(login.json.data.accessToken);
  assert.equal(claims.sub, accountId, 'token sub must equal the accountId');
  observed.loginSubMatchesAccountId = true;

  // Login must have used the real carelog-be claims projection.
  stage = 'carelog-be claims read during login';
  rows = await waitForAccessLog((r) => countClaims200(r, accountId).length >= 1);
  observed.claimsGet200 = countClaims200(rows, accountId).length;
  assert.ok(observed.claimsGet200 >= 1, 'carelog-be claims GET must answer 200 during login');

  // 5. Wrong password is rejected.
  stage = 'Carelog wrong-password login through Gateway';
  const wrong = await send('POST', `${base}/api/v1/auth/login`, {
    body: { userId: carelog.userId, password: 'WrongPassword-9' },
  });
  expectStatus(wrong, 401, 'Carelog wrong-password login through Gateway');

  // 6. Replay with the same Idempotency-Key and body: must answer 201 and must not send another enrollment PUT.
  stage = 'Carelog registration replay through Gateway';
  const putsBeforeReplay = countPuts(await readAccessLog(), accountId).length;
  const replay = await send('POST', `${base}/api/v1/auth/carelog/registration`, {
    headers: { 'idempotency-key': idempotencyKey },
    body: carelog,
  });
  expectStatus(replay, 201, 'Carelog registration replay through Gateway');
  observed.replayStatus = replay.status;
  observed.replayMessage = typeof replay.json?.message === 'string' && replay.json.message.length <= 120
    ? replay.json.message
    : '(none)';
  const usersAfterReplay = psqlRows('carelog_be_e2e',
    `SELECT count(*) FROM users WHERE external_account_id = '${accountId}'`);
  observed.carelogUserRowsAfterReplay = Number(usersAfterReplay[0][0]);
  assert.equal(observed.carelogUserRowsAfterReplay, 1, 'replay must not create a second carelog-be row');
  // A late write from the replay could land after the response; wait the full window before counting.
  await new Promise((resolve) => setTimeout(resolve, 3000));
  observed.enrollmentPutsDuringReplay = countPuts(await readAccessLog(), accountId).length - putsBeforeReplay;
  assert.equal(observed.enrollmentPutsDuringReplay, 0, 'replay must not send another enrollment PUT');
  stage = 'replay complete';

  const summary = [
    'Carelog real-registration E2E: PASS (carelog-be enrollment and claims, no stub; Finance disabled)',
    'CARELOG_ENROLLMENT_TARGET=real',
    `registration:${observed.registration} core_operation:${observed.coreOperationState}`,
    `carelog_be: enrollment_put_count:${observed.enrollmentPutCount} put_status:${observed.enrollmentPutStatuses} users:${observed.carelogUserRows} receipts:${observed.carelogReceiptRows}`,
    `enrollment_transfer: ${observed.enrollmentChunked}`,
    `login:200 sub_matches_accountId:${observed.loginSubMatchesAccountId} claims_get_200:${observed.claimsGet200}`,
    'wrong_password:401',
    `replay_same_key: status:${observed.replayStatus} message="${observed.replayMessage}" users_after:${observed.carelogUserRowsAfterReplay} enrollment_puts_during_replay:${observed.enrollmentPutsDuringReplay}`,
  ];
  console.log(summary.join('\n'));
  if (process.env.GITHUB_STEP_SUMMARY) {
    await appendFile(process.env.GITHUB_STEP_SUMMARY, [
      '## Carelog real-registration E2E',
      '',
      ...summary.map((line) => `- ${line}`),
      '',
    ].join('\n'));
  }
}

main().catch((error) => {
  console.error(`Carelog real-registration E2E: FAIL at stage "${stage}"`);
  console.error(error?.message ?? 'unknown error');
  process.exit(1);
});
